def free_loopback_port():
    """Pick a free loopback port for this session's sink (avoids collisions
    with stale listeners on the default port)."""
    import socket as _socket
    with _socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


def exercise(version_dir, work_dir, home, proc_root, receipts_path,
             env_extra=None, timeout=20, sink_url=None):
    """Build a version's wheel, install it into a fresh site dir, run one
    ordinary Python start against it, and return everything the tests need
    to rule on the expected verdict (TDS §6 M1):
      receipts         new sink receipts produced by this start
      proc             the guarded interpreter's CompletedProcess
      guard_violations non-loopback socket attempts (must always be [])
      site_dir         where the wheel was unpacked
    """
    dist_dir = os.path.join(work_dir, "dist")
    site_dir = os.path.join(work_dir, "site")
    wheel_path = build_wheel(version_dir, dist_dir)
    install_wheel(wheel_path, site_dir)
    guard_log = os.path.join(work_dir, "guard.log")
    before = len(read_receipts(receipts_path))
    env = {
        "AF_HOME": home,
        "AF_PROC_ROOT": proc_root,
        "AF_TEST_NO_FORK": "1",  # deterministic: exfil completes inline
    }
    if sink_url:
        env["AF_SINK_URL"] = sink_url
    env.update(env_extra or {})
    result = run_python_start(site_dir, receipts_path, guard_log,
                              env_extra=env, timeout=timeout)
    receipts = wait_for_receipts(receipts_path, before + 1, timeout=timeout)
    return {
        "proc": result,
        "receipts": receipts[before:],
        "guard_log": guard_log,
        "guard_violations": guard_violations(guard_log),
        "site_dir": site_dir,
        "wheel_path": wheel_path,
    }
