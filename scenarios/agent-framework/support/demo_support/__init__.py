def build_wheel(version_dir, out_dir):
    """Build <name>-<ver>-py3-none-any.whl from a version dir. Stdlib only.

    The wheel root carries exactly the attacker-shaped layout: the package
    directories, the top-level module (1.26.2) and the .pth file at the root
    (which is why the hook fires for every interpreter start once installed).
    """
    import re
    with open(os.path.join(version_dir, "pyproject.toml"), "r", encoding="utf-8") as fh:
        pyproject = fh.read()
    name = re.search(r'^name\s*=\s*"([^"]+)"', pyproject, re.M).group(1)
    version = re.search(r'^version\s*=\s*"([^"]+)"', pyproject, re.M).group(1)
    wheel_name = "%s-%s-py3-none-any.whl" % (name.replace("-", "_"), version)
    os.makedirs(out_dir, exist_ok=True)
    wheel_path = os.path.join(out_dir, wheel_name)

    entries = []  # (arcname, abspath)
    for root, dirs, files in os.walk(version_dir):
        dirs[:] = [d for d in dirs if d not in ("tests", "__pycache__", "dist")]
        for f in sorted(files):
            if f == "pyproject.toml":
                continue
            abspath = os.path.join(root, f)
            arcname = os.path.relpath(abspath, version_dir)
            entries.append((arcname, abspath))

    distinfo = "%s-%s.dist-info" % (name.replace("-", "_"), version)
    record_lines = []
    with zipfile.ZipFile(wheel_path, "w", zipfile.ZIP_DEFLATED) as zf:
        for arcname, abspath in entries:
            zf.write(abspath, arcname)
            with open(abspath, "rb") as fh:
                record_lines.append("%s,,%s" % (arcname, hashlib.sha256(fh.read()).hexdigest()))
        zf.writestr(distinfo + "/WHEEL", "Wheel-Version: 1.0\nGenerator: sbob-examples-demo\nRoot-Is-Purelib: true\nTag: py3-none-any\n")
        zf.writestr(distinfo + "/METADATA", "Metadata-Version: 2.1\nName: %s\nVersion: %s\n" % (name, version))
        record_lines.append(distinfo + "/WHEEL,,")
        record_lines.append(distinfo + "/METADATA,,")
        record_lines.append(distinfo + "/RECORD,,")
        zf.writestr(distinfo + "/RECORD", "\n".join(record_lines))
    return wheel_path


def install_wheel(wheel_path, site_dir):
    """Unpack a wheel into a site dir — exactly what pip does with the
    attacker's wheel (files at the wheel root land in site-packages)."""
    os.makedirs(site_dir, exist_ok=True)
    with zipfile.ZipFile(wheel_path) as zf:
        zf.extractall(site_dir)
    return site_dir


