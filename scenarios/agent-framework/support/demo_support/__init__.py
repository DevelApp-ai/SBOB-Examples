def start_sink(receipts_path, port=8099):
    """Start the loopback sink server as a subprocess; returns the handle.

    Binds 127.0.0.1 only, then PROVES the round trip with a probe POST before
    returning: a stale listener from a previous crashed run must never
    silently answer healthz while writing receipts somewhere else.
    """
    env = dict(os.environ)
    env["AF_SINK_RECEIPTS"] = receipts_path
    env["AF_SINK_PORT"] = str(port)
    proc = subprocess.Popen(
        [sys.executable, os.path.join(HERE, "..", "..", "sink", "sink_server.py")],
        env=env,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    import urllib.request
    base = "http://127.0.0.1:%d" % port
    deadline = time.time() + 15
    while time.time() < deadline:
        try:
            urllib.request.urlopen(base + "/healthz", timeout=1)
            break
        except Exception:
            if proc.poll() is not None:
                raise RuntimeError("sink server exited early with %s" % proc.returncode)
            time.sleep(0.1)
    else:
        raise RuntimeError("sink server did not become ready")
    # Round-trip probe: this sink must write THIS receipts file.
    probe = base64.b64encode(zlib.compress(json.dumps({"probe": True}).encode()))
    before = len(read_receipts(receipts_path))
    request = urllib.request.Request(base + "/?t=probe", data=probe,
                                    headers={"User-Agent": "demo-support-probe"},
                                    method="POST")
    urllib.request.urlopen(request, timeout=5)
    receipts = wait_for_receipts(receipts_path, before + 1, timeout=10)
    if len(receipts) <= before:
        proc.terminate()
        raise RuntimeError("sink round-trip probe failed: stale listener?")
    return proc


def read_receipts(receipts_path):
    if not os.path.exists(receipts_path):
        return []
    out = []
    with open(receipts_path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                out.append(json.loads(line))
    return out


def wait_for_receipts(receipts_path, count, timeout=20):
    deadline = time.time() + timeout
    while time.time() < deadline:
        if len(read_receipts(receipts_path)) >= count:
            return read_receipts(receipts_path)
        time.sleep(0.1)
    return read_receipts(receipts_path)


def decode_payload(receipt):
    """Decode a receipt into the stealer's JSON document.

    The POST body is base64(zlib(JSON)) text (incident shape); the sink
    stores the raw body base64-encoded, so decoding is two layers.
    """
    body_text = base64.b64decode(receipt["body_b64"])
    payload = base64.b64decode(body_text)
    return json.loads(zlib.decompress(payload).decode("utf-8"))


