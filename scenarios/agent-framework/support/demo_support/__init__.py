GUARD_BOOTSTRAP = r"""
import sys, os
_guard_log = os.environ.get("AF_GUARD_LOG", "")
def _af_guard(event, args):
    if event == "socket.connect":
        addr = args[1]
        host = None
        if isinstance(addr, tuple) and addr:
            host = addr[0]
        elif isinstance(addr, (bytes, bytearray)):
            host = str(addr)
        allowed = {"127.0.0.1", "::1", "localhost", "", None}
        if host not in allowed:
            with open(_guard_log, "a", encoding="utf-8") as fh:
                fh.write("SOCKET_VIOLATION %r\n" % (addr,))
            os._exit(97)
sys.addaudithook(_af_guard)
import site
site.addsitedir(sys.argv[1])
"""


def run_python_start(site_dir, receipts_path, guard_log, env_extra=None, timeout=60):
    """One 'ordinary Python startup' against an installed version.

    site.addsitedir() performs exactly the .pth processing site-packages does
    at startup: the hook fires with no import of agent_framework. The audit
    hook makes any non-loopback connect a loud failure (exit 97 + log line).
    """
    env = dict(os.environ)
    env.update(env_extra or {})
    env.setdefault("AF_SINK_RECEIPTS", receipts_path)
    env["AF_GUARD_LOG"] = guard_log
    return subprocess.run(
        [sys.executable, "-c", GUARD_BOOTSTRAP, site_dir],
        env=env,
        capture_output=True,
        text=True,
        timeout=timeout,
    )


def guard_violations(guard_log):
    if not os.path.exists(guard_log):
        return []
    with open(guard_log, "r", encoding="utf-8") as fh:
        return [ln for ln in fh.read().splitlines() if ln.startswith("SOCKET_VIOLATION")]


